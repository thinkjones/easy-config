const policyHeader = "# Generated by ezc from recipients.yaml. Do not edit.\n"

func (b *sopsBackend) NewKey() (string, []byte, error) {
	id, err := age.GenerateX25519Identity()
	if err != nil {
		return "", nil, fmt.Errorf("could not create a key: %w", err)
	}
	public := id.Recipient().String()
	return public, []byte("# public key: " + public + "\n" + id.String() + "\n"), nil
}

// PublicKey reads the first identity in keyFile. No error carries the file's text, which is the private key.
func (b *sopsBackend) PublicKey(keyFile string) (string, error) {
	data, err := os.ReadFile(keyFile)
	if errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("%s: no key file: %w", keyFile, backend.ErrNoKey)
	}
	if err != nil {
		return "", fmt.Errorf("%s: could not read the key file", keyFile)
	}
	if !slices.ContainsFunc(strings.Split(string(data), "\n"), func(l string) bool {
		l = strings.TrimSpace(l)
		return l != "" && !strings.HasPrefix(l, "#")
	}) {
		return "", fmt.Errorf("%s: holds no key: %w", keyFile, backend.ErrNoKey)
	}
	ids, err := age.ParseIdentities(bytes.NewReader(data))
	if err != nil {
		return "", fmt.Errorf("%s: the key file cannot be read as keys", keyFile)
	}
	for _, id := range ids {
		if x, ok := id.(*age.X25519Identity); ok {
			return x.Recipient().String(), nil
		}
	}
	return "", fmt.Errorf("%s: holds no key: %w", keyFile, backend.ErrNoKey)
}

func (b *sopsBackend) WritePolicy(dir string, recipients []string) error {
	if len(recipients) == 0 {
		return fmt.Errorf("%s: no recipients to write a policy for", dir)
	}
	policy := policyHeader + "creation_rules:\n  - path_regex: \\.enc\\.yaml$\n    age: " + strings.Join(recipients, ",") + "\n"
	return writeFileAtomic(dir+string(os.PathSeparator)+PolicyFile, []byte(policy))
}

// PolicyRecipients reads the policy as sops does for a new file: the age keys of the first rule whose path_regex
// matches the file's name. A rule that names any other kind of key is not one this can answer for.
func (b *sopsBackend) PolicyRecipients(path string) ([]string, error) {
	if err := b.requirePolicy(path); err != nil {
		return nil, err
	}
	policy := filepath.Join(filepath.Dir(path), PolicyFile)
	data, err := os.ReadFile(policy)
	if err != nil {
		return nil, fmt.Errorf("%s: could not read this file", policy)
	}
	var doc struct {
		Rules []map[string]any `yaml:"creation_rules"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s: not valid YAML", policy)
	}
	base := filepath.Base(path)
	for _, rule := range doc.Rules {
		pattern, _ := rule["path_regex"].(string)
		if re, err := regexp.Compile(pattern); err != nil || !re.MatchString(base) {
			continue
		}
		list, isText := rule["age"].(string)
		for field := range rule {
			if field != "path_regex" && field != "age" {
				isText = false
			}
		}
		if !isText {
			return nil, fmt.Errorf("%s: its rule for %s names keys ezc cannot list", policy, base)
		}
		keys := []string{}
		for _, key := range strings.Split(list, ",") {
			if key = strings.TrimSpace(key); key != "" {
				keys = append(keys, key)
			}
		}
		slices.Sort(keys)
		return slices.Compact(keys), nil
	}
	return nil, &kindError{fmt.Sprintf("%s has no rule that matches %s.", policy, base), backend.ErrNoPolicy}
}

func (b *sopsBackend) ToolHint(goos string) string {
	if goos == "windows" {
		return "Download it from https://github.com/getsops/sops/releases."
	}
	return "Install it with `brew install sops`, or download it from https://github.com/getsops/sops/releases."
}

func (b *sopsBackend) BrewFormula() string { return "sops" }
