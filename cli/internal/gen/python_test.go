package gen

import (
	"bytes"
	"flag"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"

	"github.com/thinkjones/easy-config/cli/internal/manifest"
)

var update = flag.Bool("update", false, "rewrite golden files")

const golden = "testdata/config.py.golden"

const testManifest = `
schemaVersion: v1
required:
  LLM_API_KEY: {type: secret, desc: "Key for the LLM provider."}
  BATCH_SIZE: {type: int, desc: "Items per batch.", min: 1, max: 100}
  DIGEST_OUTPUT: {type: enum, desc: "Where the digest goes.", values: [file, s3]}
  SITE: {type: url, desc: "Public site."}
optional:
  DIGEST_OUTPUT_PATH: {type: path, desc: "Digest file.", requiredWhen: {var: DIGEST_OUTPUT, equals: file}}
  DEBUG: {type: bool, desc: "Verbose logging."}
`

func gen(t *testing.T) []byte {
	t.Helper()
	var m manifest.Manifest
	if err := yaml.Unmarshal([]byte(testManifest), &m); err != nil {
		t.Fatal(err)
	}
	out, err := Python(m, ".ezc/manifest.yaml")
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestPythonGolden(t *testing.T) {
	got := gen(t)
	if *update {
		if err := os.WriteFile(golden, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("generated output differs from %s; rerun with -update if intended", golden)
	}
}

func TestPythonHeader(t *testing.T) {
	got := string(gen(t))
	if first, _, _ := strings.Cut(got, "\n"); first != "# GENERATED by ezc from .ezc/manifest.yaml — DO NOT EDIT." {
		t.Errorf("first line %q", first)
	}
	if !strings.Contains(got, "# Regenerate:  ezc codegen python -o <this file>") {
		t.Error("no Regenerate line")
	}
	for _, bad := range []string{"fs" + "config", "mise"} {
		if strings.Contains(got, bad) {
			t.Errorf("contains %q", bad)
		}
	}
}

func TestPythonIsDeterministic(t *testing.T) {
	if !bytes.Equal(gen(t), gen(t)) {
		t.Error("two calls differ")
	}
}

func TestGoldenIsValidPython(t *testing.T) {
	py, err := exec.LookPath("python3")
	if err != nil {
		t.Skip("python3 not on PATH")
	}
	path, _ := filepath.Abs(golden)
	out, err := exec.Command(py, "-c", "import ast,sys; ast.parse(open(sys.argv[1]).read())", path).CombinedOutput()
	if err != nil {
		t.Errorf("golden is not valid Python: %v\n%s", err, out)
	}
}
