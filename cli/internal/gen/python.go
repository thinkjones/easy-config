// Package gen holds the per-language config generators. One generator per
// language, all driven by the same manifest, so the languages cannot disagree
// about what the repo requires.
package gen

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/thinkjones/easy-config/cli/internal/check"
	"github.com/thinkjones/easy-config/cli/internal/manifest"
)

// Python emits an idiomatic pydantic v2 model.
//
// pydantic rather than a hand-rolled loader because it is what a Python
// developer expects, it already produces good multi-error messages, and the
// int/enum/URL coercion and bounds come free — this generator only has to
// describe the shape.
//
// Deliberately NOT pydantic-settings: pydantic itself is usually already a
// dependency (langchain pulls it in), and reading os.environ explicitly is a
// dozen lines. Adding a package to read environment variables is not a trade
// most repos want forced on them.
func Python(m manifest.Manifest, manifestPath string) ([]byte, error) {
	for _, e := range m.All() {
		if pythonKeywords[e.Name] {
			return nil, fmt.Errorf("cannot generate Python: %s is a Python keyword", e.Name)
		}
		if strings.HasPrefix(e.Name, "_") {
			return nil, fmt.Errorf("cannot generate Python: %s starts with an underscore, which pydantic treats as private", e.Name)
		}
	}

	var b bytes.Buffer

	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	p("# GENERATED by ezc from .ezc/manifest.yaml — DO NOT EDIT.")
	p("#")
	p("# Source:      %s", manifestPath)
	p("# Regenerate:  ezc codegen python -o <this file>")
	p("# CI diffs this file against a fresh generation, so an edit here is a")
	p("# build failure, not a surprise at runtime.")
	p("#")
	p("# Every field is required unless typed as optional. There are no defaults")
	p("# anywhere in this file, by design: a default is how a missing production")
	p("# value becomes a silent fallback.")
	p("")
	p("# ruff: noqa: E501")
	p("# Docstrings are the manifest's descriptions, verbatim. Reflowing them here")
	p("# would make the two texts differ and break grepping for a variable's")
	p("# explanation across the manifest and the generated code.")
	p("")
	p("from __future__ import annotations")
	p("")
	p("import os")
	p("from typing import Any, Literal")
	p("")
	p("from pydantic import BaseModel, ConfigDict, Field, ValidationError")
	p("from pydantic_core import core_schema")
	p("")
	p("")
	p("class Secret(str):")
	p("    \"\"\"A string that does not reveal itself in tracebacks or logs.")
	p("")
	p("    repr() is what ends up in a pydantic error, a pytest diff and most")
	p("    logging calls, so redacting it there covers the realistic leak paths.")
	p("    str() still returns the real value — the point is to make leaking")
	p("    deliberate rather than accidental.")
	p("    \"\"\"")
	p("")
	p("    __slots__ = ()")
	p("")
	p("    def __repr__(self) -> str:  # noqa: D105")
	p("        return \"Secret('***')\"")
	p("")
	p("    @classmethod")
	p("    def __get_pydantic_core_schema__(")
	p("        cls, source_type: Any, handler: Any")
	p("    ) -> core_schema.CoreSchema:")
	p("        # A bare str subclass is not a pydantic type. Validate as a str,")
	p("        # then wrap — so coercion still works and the field stays typed.")
	p("        del source_type, handler")
	p("        return core_schema.no_info_after_validator_function(")
	p("            cls, core_schema.str_schema(min_length=1)")
	p("        )")
	p("")
	p("")
	p("class Env(BaseModel):")
	p("    \"\"\"Validated view of this repo's environment.\"\"\"")
	p("")
	p("    model_config = ConfigDict(frozen=True, extra=\"ignore\")")
	p("")

	for _, e := range m.All() {
		_, isRequired := m.Required[e.Name]
		p("    %s", fieldLine(e.Name, e.Var, isRequired))
		p("    \"\"\"%s\"\"\"", escapeDoc(e.Var.Desc))
		p("")
	}

	p("")
	p("_NAMES = (")
	for _, e := range m.All() {
		p("    %q,", e.Name)
	}
	p(")")
	p("")
	p("")
	// The emitted _present must agree with check.Run, which is the OTHER
	// validator over the same manifest. Where they disagree, `ezc env`
	// passes and the application then dies on the identical environment —
	// which is precisely what happened when a CI workflow named a GitHub
	// secret that did not exist: the expansion is the EMPTY STRING, not an
	// absent variable, so check.Run called it missing (and optional, so fine)
	// while the generated loader called it a present value one character too
	// short. Same manifest, same environment, opposite verdicts, and the
	// error surfaced a step later with a message that named the wrong thing.
	//
	// So this mirrors check.Run exactly: trim, then treat empty and the
	// conventional placeholder words as ABSENT. Trimming is not cosmetic —
	// check.Run validates the TRIMMED value, so a loader that kept the raw one
	// would be validating a different string than the tool that just approved
	// it. It also quietly fixes the trailing newline a pasted secret carries.
	p("_PLACEHOLDERS = frozenset(")
	p("    {")
	for _, name := range check.PlaceholderWords() {
		p("        %q,", name)
	}
	p("    }")
	p(")")
	p("")
	p("")
	p("def _present(value: str) -> bool:")
	p("    \"\"\"Is this raw environment value a real one?")
	p("")
	p("    Mirrors ezc's own validator. An unset variable, an empty or")
	p("    whitespace-only one, and an unfilled placeholder are all ABSENT — not")
	p("    present-but-invalid. A workflow naming a secret that does not exist")
	p("    substitutes the empty string, and that must not read as a value.")
	p("    \"\"\"")
	p("    stripped = value.strip()")
	p("    return bool(stripped) and stripped.lower() not in _PLACEHOLDERS")
	p("")
	p("")
	p("def load() -> Env:")
	p("    \"\"\"Build Env from os.environ, or raise EnvError naming every problem.")
	p("")
	p("    Collects all failures rather than stopping at the first: a fresh clone")
	p("    should get one list, not ten sequential fix-and-retry cycles.")
	p("    \"\"\"")
	p("    raw = {")
	p("        name: os.environ[name].strip()")
	p("        for name in _NAMES")
	p("        if name in os.environ and _present(os.environ[name])")
	p("    }")
	p("    try:")
	p("        return Env.model_validate(raw)")
	p("    except ValidationError as exc:")
	p("        raise EnvError(_format(exc)) from None")
	p("")
	p("")
	p("class EnvError(RuntimeError):")
	p("    \"\"\"The environment is incomplete or invalid.\"\"\"")
	p("")
	p("")
	p("_DESCRIPTIONS = {")
	for _, e := range m.All() {
		p("    %q: %q,", e.Name, e.Var.Desc)
	}
	p("}")
	p("")
	p("")
	p("def _format(exc: ValidationError) -> str:")
	p("    lines = [\"Env validation failed:\"]")
	p("    for err in exc.errors():")
	p("        name = str(err[\"loc\"][0]) if err[\"loc\"] else \"?\"")
	p("        desc = _DESCRIPTIONS.get(name, \"\")")
	p("        # Never interpolate err['input']: for a secret that would print")
	p("        # the value into the exception message.")
	p("        lines.append(f\"  {name} — {desc}\" if desc else f\"  {name}\")")
	p("        lines.append(f\"      {err['msg']}\")")
	p("    return \"\\n\".join(lines)")

	return b.Bytes(), nil
}

func fieldLine(name string, v manifest.Var, required bool) string {
	typ := pyType(v)
	var constraints []string
	if v.Min != nil {
		constraints = append(constraints, fmt.Sprintf("ge=%d", *v.Min))
	}
	if v.Max != nil {
		constraints = append(constraints, fmt.Sprintf("le=%d", *v.Max))
	}

	if !required {
		typ += " | None"
		constraints = append([]string{"default=None"}, constraints...)
	}
	if len(constraints) == 0 {
		return fmt.Sprintf("%s: %s", name, typ)
	}
	return fmt.Sprintf("%s: %s = Field(%s)", name, typ, strings.Join(constraints, ", "))
}

func pyType(v manifest.Var) string {
	switch v.Type {
	case manifest.TypeInt:
		return "int"
	case manifest.TypeBool:
		return "bool"
	case manifest.TypeSecret:
		return "Secret"
	case manifest.TypeEnum:
		quoted := make([]string, 0, len(v.Values))
		for _, val := range v.Values {
			quoted = append(quoted, fmt.Sprintf("%q", val))
		}
		return "Literal[" + strings.Join(quoted, ", ") + "]"
	default: // str, url, path — all strings to Python; the distinction drives docs
		return "str"
	}
}

// pythonKeywords are Python 3's reserved words, none of which can name a field.
// The soft keywords (match, case, type, _) can, so they are not here.
var pythonKeywords = map[string]bool{
	"False": true, "None": true, "True": true, "and": true, "as": true, "assert": true,
	"async": true, "await": true, "break": true, "class": true, "continue": true,
	"def": true, "del": true, "elif": true, "else": true, "except": true, "finally": true,
	"for": true, "from": true, "global": true, "if": true, "import": true, "in": true,
	"is": true, "lambda": true, "nonlocal": true, "not": true, "or": true, "pass": true,
	"raise": true, "return": true, "try": true, "while": true, "with": true, "yield": true,
}

// escapeDoc makes s safe between triple quotes, where it still reads as s: a
// backslash is doubled and every " is escaped, so no run of quotes can close
// the docstring or join the closing ones.
func escapeDoc(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	return strings.ReplaceAll(s, `"`, `\"`)
}
